#!/usr/bin/env node
/**
 * Generate the D1 migration that seeds the organisation review queue.
 *
 * The candidate batches live in the dataset repository
 * (`data/intake/organisations/<batch>/batch-*.json`). The atlas needs them in
 * D1 so `/review` can work them, but a Worker has no filesystem and this
 * deployment has no way to run an ad-hoc import against production D1. So the
 * rows are compiled into an ordinary migration, which the runtime migrator
 * applies once, exactly like the schema before it.
 *
 * Inserts are batched (50 rows per statement) because the migrator hands D1 one
 * statement at a time: 1,292 single-row inserts would be 1,292 round trips on a
 * cold start.
 *
 * Re-runnable: `insert or ignore` keyed on the candidate id, so regenerating
 * and re-applying cannot duplicate a row or clobber a review decision.
 *
 *   node scripts/build-org-intake-migration.mjs \
 *     --src ../africa-energy-software-map \
 *     --batch sweep-2026-08-epc-minigrid
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = new Map();
for (let i = 2; i < process.argv.length; i += 2) args.set(process.argv[i], process.argv[i + 1]);

const src = args.get("--src") ?? process.env.AESM_SRC;
const batch = args.get("--batch") ?? "sweep-2026-08-epc-minigrid";
const out = args.get("--out") ?? join(REPO, "migrations", "0004_organisation_candidates.sql");
if (!src) {
  console.error("pass --src /path/to/africa-energy-software-map (or set AESM_SRC)");
  process.exit(1);
}

const dir = join(src, "data/intake/organisations", batch);
if (!existsSync(dir)) {
  console.error(`no such intake batch: ${dir}`);
  process.exit(1);
}

/** SQL string literal. Doubling the quote is the whole escape rule in SQLite. */
const q = (value) => `'${String(value ?? "").replace(/'/g, "''")}'`;

const files = readdirSync(dir).filter((f) => /^batch-\d+\.json$/.test(f)).sort();
const rows = [];
let flaggedNames = new Set();
const flagPath = join(src, "data/research-queue", batch, "flagged-personal.json");
if (existsSync(flagPath)) {
  for (const item of JSON.parse(readFileSync(flagPath, "utf8"))) {
    if (item?.name) flaggedNames.add(String(item.name));
  }
}

for (const file of files) {
  const payload = JSON.parse(readFileSync(join(dir, file), "utf8"));
  for (const c of payload.candidates ?? []) {
    rows.push({
      id: c.candidateId,
      batch_id: payload.batchId,
      source_kind: payload.source?.kind ?? "",
      name: c.submittedName,
      website: c.submittedWebsite ?? "",
      countries: c.submittedHeadquarters ?? "",
      role_ids: (c.suggestedRoleIds ?? []).join(","),
      segment_ids: (c.suggestedSegmentIds ?? []).join(","),
      actor_group_id: c.suggestedActorGroupId ?? "",
      evidence_note: c.submittedNotes ?? "",
      source_url: (c.sourceLeads ?? [])[0] ?? "",
      // Surfaced in the queue so an editor can see which names the personal-name
      // detector was unsure about, rather than that judgement being invisible.
      flagged_personal: flaggedNames.has(c.submittedName) ? 1 : 0,
    });
  }
}

const COLS = [
  "id", "batch_id", "source_kind", "name", "website", "countries", "role_ids",
  "segment_ids", "actor_group_id", "evidence_note", "source_url", "flagged_personal",
];

const chunks = [];
for (let i = 0; i < rows.length; i += 50) chunks.push(rows.slice(i, i + 50));

const sql = `-- Organisation review queue, seeded from the dataset repository's
-- candidate batches: ${batch}
--
-- GENERATED by scripts/build-org-intake-migration.mjs — do not hand-edit.
-- Regenerate after a new sweep; \`insert or ignore\` keeps re-application safe
-- and never overwrites a review decision already recorded against a row.
--
-- ${rows.length} candidates from ${files.length} batch files.

create table if not exists organisation_candidates (
  id text primary key,
  batch_id text not null default '',
  source_kind text not null default '',
  name text not null,
  website text not null default '',
  countries text not null default '',
  role_ids text not null default '',
  segment_ids text not null default '',
  actor_group_id text not null default '',
  evidence_note text not null default '',
  source_url text not null default '',
  flagged_personal integer not null default 0,
  status text not null default 'received',
  note text not null default '',
  slug text not null default '',
  version integer not null default 1,
  reviewed_by_user_id text not null default '',
  reviewed_by_email text not null default '',
  reviewed_at text,
  created_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

create index if not exists organisation_candidates_status_idx
  on organisation_candidates (status, name);

create unique index if not exists organisation_candidates_slug_uidx
  on organisation_candidates (slug)
  where slug <> '';

${chunks.map((chunk) => `insert or ignore into organisation_candidates (${COLS.join(", ")}) values\n${
  chunk.map((r) => `  (${COLS.map((c) => (c === "flagged_personal" ? r[c] : q(r[c]))).join(", ")})`).join(",\n")
};`).join("\n\n")}
`;

writeFileSync(out, sql);
console.log(`wrote ${out}`);
console.log(`  candidates: ${rows.length} from ${files.length} batch files`);
console.log(`  flagged as possible natural persons: ${rows.filter((r) => r.flagged_personal).length}`);
console.log(`  insert statements: ${chunks.length} (50 rows each)`);
console.log(`  size: ${(sql.length / 1024).toFixed(0)} KB`);
